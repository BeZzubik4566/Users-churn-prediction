CREATE SCHEMA IF NOT EXISTS raw;
CREATE SCHEMA IF NOT EXISTS analytics;
CREATE SCHEMA IF NOT EXISTS ml;

-- Обучающая выборка: здесь есть целевая переменная churn.
CREATE TABLE IF NOT EXISTS raw.customers_train (
    row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_period INTEGER NOT NULL CHECK (client_period >= 0),
    monthly_spending NUMERIC(10, 2) NOT NULL CHECK (monthly_spending >= 0),
    total_spent NUMERIC(12, 2) NOT NULL CHECK (total_spent >= 0),
    sex VARCHAR(20) NOT NULL,
    is_senior_citizen SMALLINT NOT NULL CHECK (is_senior_citizen IN (0, 1)),
    has_partner VARCHAR(30) NOT NULL,
    has_child VARCHAR(30) NOT NULL,
    has_phone_service VARCHAR(30) NOT NULL,
    has_multiple_phone_numbers VARCHAR(40) NOT NULL,
    has_internet_service VARCHAR(40) NOT NULL,
    has_online_security_service VARCHAR(40) NOT NULL,
    has_online_backup VARCHAR(40) NOT NULL,
    has_device_protection VARCHAR(40) NOT NULL,
    has_tech_support_access VARCHAR(40) NOT NULL,
    has_online_tv VARCHAR(40) NOT NULL,
    has_movie_subscription VARCHAR(40) NOT NULL,
    has_contract_phone VARCHAR(40) NOT NULL,
    is_billing_paperless VARCHAR(30) NOT NULL,
    payment_method VARCHAR(60) NOT NULL,
    churn SMALLINT NOT NULL CHECK (churn IN (0, 1))
);

-- Тестовая выборка: целевой переменной churn в исходном файле нет.
CREATE TABLE IF NOT EXISTS raw.customers_test (
    row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_period INTEGER NOT NULL CHECK (client_period >= 0),
    monthly_spending NUMERIC(10, 2) NOT NULL CHECK (monthly_spending >= 0),
    total_spent NUMERIC(12, 2) NOT NULL CHECK (total_spent >= 0),
    sex VARCHAR(20) NOT NULL,
    is_senior_citizen SMALLINT NOT NULL CHECK (is_senior_citizen IN (0, 1)),
    has_partner VARCHAR(30) NOT NULL,
    has_child VARCHAR(30) NOT NULL,
    has_phone_service VARCHAR(30) NOT NULL,
    has_multiple_phone_numbers VARCHAR(40) NOT NULL,
    has_internet_service VARCHAR(40) NOT NULL,
    has_online_security_service VARCHAR(40) NOT NULL,
    has_online_backup VARCHAR(40) NOT NULL,
    has_device_protection VARCHAR(40) NOT NULL,
    has_tech_support_access VARCHAR(40) NOT NULL,
    has_online_tv VARCHAR(40) NOT NULL,
    has_movie_subscription VARCHAR(40) NOT NULL,
    has_contract_phone VARCHAR(40) NOT NULL,
    is_billing_paperless VARCHAR(30) NOT NULL,
    payment_method VARCHAR(60) NOT NULL
);

-- Здесь сохраняются прогнозы модели по строкам из customers_test.
CREATE TABLE IF NOT EXISTS ml.predictions (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_row_id BIGINT NOT NULL REFERENCES raw.customers_test(row_id) ON DELETE CASCADE,
    churn_probability DOUBLE PRECISION NOT NULL CHECK (churn_probability >= 0 AND churn_probability <= 1),
    predicted_churn SMALLINT NOT NULL CHECK (predicted_churn IN (0, 1)),
    model_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (test_row_id, model_name)
);

-- Метрики качества на отложенной валидационной выборке.
CREATE TABLE IF NOT EXISTS ml.model_metrics (
    metric_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name VARCHAR(100) NOT NULL,
    accuracy DOUBLE PRECISION NOT NULL,
    precision_score DOUBLE PRECISION NOT NULL,
    recall_score DOUBLE PRECISION NOT NULL,
    f1_score DOUBLE PRECISION NOT NULL,
    roc_auc DOUBLE PRECISION NOT NULL,
    train_rows INTEGER NOT NULL,
    validation_rows INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_customers_train_churn
    ON raw.customers_train (churn);

CREATE INDEX IF NOT EXISTS idx_customers_train_contract
    ON raw.customers_train (has_contract_phone);
